import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import test from 'node:test';

const migration = readFileSync(new URL('../../supabase/migrations/20261025152931_project_preview_videos.sql', import.meta.url), 'utf8');
const owner = '11111111-1111-4111-8111-111111111111', other = '22222222-2222-4222-8222-222222222222';
const project = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', foreign = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
test('SQL: ownership, grants, verified uploads, constraints, public projection and safe replacement/removal', async () => {
  assert.ok(process.env.PORTFOLIO_TEST_PGLITE_MODULE, 'Set PORTFOLIO_TEST_PGLITE_MODULE to the existing disposable PGlite runtime');
  const { PGlite } = await import(pathToFileURL(process.env.PORTFOLIO_TEST_PGLITE_MODULE).href);
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create schema auth; create schema private; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      grant usage on schema auth to authenticated;
      create table public.projects(id uuid primary key, user_id uuid references auth.users(id) on delete cascade, slug text, visibility text);
      alter table public.projects enable row level security;
      create policy own_projects on public.projects to authenticated using(user_id=auth.uid());
      grant select on public.projects to authenticated;
      create function private.set_updated_at() returns trigger language plpgsql as $$begin new.updated_at=now(); return new; end$$;
      create function private.canonical_portfolio_owner_id() returns uuid language sql as $$select '${owner}'::uuid$$;
      insert into auth.users values('${owner}'),('${other}');
      insert into public.projects values('${project}','${owner}','demo','Private'),('${foreign}','${other}','other','Public');`);
    await db.exec(migration);
    const as = async (role, user = '') => db.exec(`reset role; select set_config('request.jwt.claim.sub','${user}',false); set role ${role};`);
    const rpc = async (action, input = {}, user = owner, id = project) => (await db.query('select public.manage_project_preview_video($1,$2,$3,$4::jsonb) as result', [user,id,action,JSON.stringify(input)])).rows[0].result;
    const resolve = async () => (await db.query("select * from public.public_project_preview_video('demo')")).rows;
    const path = n => `portfolio-previews/${String(n).repeat(48)}.mp4`;
    await as('authenticated', owner);
    assert.deepEqual((await db.query('select * from public.project_preview_videos')).rows, []);
    await assert.rejects(rpc('begin'), /permission denied/);
    await assert.rejects(db.query('select * from private.project_preview_video_uploads'), /permission denied/);
    await assert.rejects(db.query(`insert into public.project_preview_videos(user_id,project_id,blob_pathname,file_name,mime_type,size_bytes) values('${owner}','${project}','${path(1)}','test.mp4','video/mp4',10)`), /Unverified/);
    await as('service_role');
    await assert.rejects(rpc('begin',{},owner,foreign), /Project unavailable/);
    await assert.rejects(rpc('begin',{},owner,'cccccccc-cccc-4ccc-8ccc-cccccccccccc'), /Project unavailable/);
    const input = {pathname:path(1),name:'test.mp4',type:'video/mp4',size:10485760};
    for (const size of [0,15728641]) await assert.rejects(rpc('begin',{...input,size}), /check constraint/);
    await assert.rejects(rpc('begin',{...input,type:'text/html'}), /check constraint/);
    const first = await rpc('begin',input);
    await assert.rejects(rpc('intent',first,other), /Project unavailable/);
    const intent = await rpc('intent',first);
    assert.equal(intent.blob_pathname,input.pathname);
    await assert.rejects(rpc('finalize',{...first,pathname:path(1),mimeType:'video/mp4',sizeBytes:1}), /mismatch/);
    let result = await rpc('finalize',{...first,pathname:path(1),mimeType:'video/mp4',sizeBytes:10485760});
    assert.equal(result.video.enabled,false);
    await rpc('enabled',{enabled:true});
    await as('anon');
    await assert.rejects(db.query('select * from public.project_preview_videos'), /permission denied/);
    assert.deepEqual(await resolve(),[]); // Private + enabled.
    await as('postgres');
    await db.exec(`update public.projects set visibility='Public' where id='${project}'`);
    await as('anon');
    let publicRows = await resolve();
    assert.equal(publicRows.length,1);
    assert.deepEqual(Object.keys(publicRows[0]).sort(),['project_slug','blob_pathname','mime_type','updated_at'].sort());
    assert.equal((await db.query("select * from public.public_project_preview_video('../bad')")).rows.length,0);
    await as('authenticated',other);
    assert.equal((await db.query('select * from public.project_preview_videos')).rows.length,0);
    assert.equal((await db.query('update public.project_preview_videos set enabled=false returning id')).rows.length,0);
    await assert.rejects(db.query(`insert into public.project_preview_videos(user_id,project_id,blob_pathname,file_name,mime_type,size_bytes) values('${other}','${foreign}','${path(1)}','test.mp4','video/mp4',10485760)`), /Unverified/);
    await as('authenticated',owner);
    assert.equal((await db.query('select * from public.project_preview_videos')).rows.length,1);
    await assert.rejects(db.query("update public.project_preview_videos set created_at='infinity'"), /check constraint/);
    await assert.rejects(db.query('update public.project_preview_videos set size_bytes=0'), /Unverified|check constraint/);
    const saved=(await db.query('delete from public.project_preview_videos returning *')).rows[0];
    await db.query('insert into public.project_preview_videos(user_id,project_id,blob_pathname,file_name,mime_type,size_bytes) values($1,$2,$3,$4,$5,$6)',[saved.user_id,saved.project_id,saved.blob_pathname,saved.file_name,saved.mime_type,saved.size_bytes]);
    await db.exec('update public.project_preview_videos set enabled=false');
    await as('anon'); assert.deepEqual(await resolve(),[]);
    await as('service_role');
    await rpc('enabled',{enabled:true});
    const second = await rpc('begin',{...input,pathname:path(2)});
    // Working preview survives until verified replacement is committed.
    await as('anon'); assert.equal((await resolve())[0].blob_pathname,path(1));
    await as('service_role');
    result = await rpc('finalize',{...second,pathname:path(2),mimeType:'video/mp4',sizeBytes:10485760});
    assert.equal(result.oldPath,path(1)); assert.equal(result.video.blob_pathname,path(2)); assert.equal(result.video.enabled,false);
    assert.equal((await rpc('intent',second)).video.blob_pathname,path(2));
    await assert.rejects(rpc('intent',first), /Upload unavailable/);
    await rpc('enabled',{enabled:true});
    await as('postgres'); await db.exec(`update public.projects set visibility='Unlisted' where id='${project}'`);
    await as('anon'); assert.deepEqual(await resolve(),[]);
    await as('service_role'); assert.equal((await rpc('remove')).oldPath,path(2));
    await as('anon'); assert.deepEqual(await resolve(),[]);
    await as('postgres');
    assert.equal((await db.query('select * from public.project_preview_videos')).rows.length,0);
    await as('service_role');
    const expired=await rpc('begin',{...input,pathname:path(3)});
    await as('postgres');await db.query("update private.project_preview_video_uploads set expires_at=now()-interval '1 second' where id=$1",[expired.uploadId]);
    await as('service_role');await assert.rejects(rpc('intent',expired), /Upload expired/);
    const last=await rpc('begin',{...input,pathname:path(4)});
    await rpc('finalize',{...last,pathname:path(4),mimeType:'video/mp4',sizeBytes:10485760});
    await as('postgres');await db.exec(`delete from public.projects where id='${project}'`);
    assert.equal((await db.query('select * from public.project_preview_videos')).rows.length,0);
    assert.equal((await db.query('select * from private.project_preview_video_uploads')).rows.length,0);
  } finally { await db.close(); }
});
